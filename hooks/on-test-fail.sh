#!/bin/bash

# 한국어 주석: 테스트 혹은 빌드 실패 시 구동되는 피드백 훅입니다.
# 에러가 기록된 파일을 탐지하여 메인 에이전트 및 QA 서브 에이전트가 이를 추적하도록 돕습니다.

# 한국어 주석: 실행 중인 디렉토리 또는 Git 최상위 루트 디렉토리를 탐색하여 설정합니다.
if git rev-parse --show-toplevel >/dev/null 2>&1; then
  PROJECT_ROOT="$(git rev-parse --show-toplevel)"
else
  PROJECT_ROOT="$(pwd)"
fi
ERROR_LOG="${PROJECT_ROOT}/.tmp_artifacts/test_error.log"

echo "============================================="
echo "[!] 경고: 에이전트 하네스 테스트 실패 훅 실행됨"
echo "============================================="

if [ -f "${ERROR_LOG}" ]; then
  echo "[+] 에러 로그 파일 감지됨. 상세 내용:"
  echo "---------------------------------------------"
  cat "${ERROR_LOG}"
  echo "---------------------------------------------"
  echo "[+] 이 로그는 QA 테스터 에이전트에게 자동 전송됩니다."
else
  echo "[-] 에러 로그를 찾을 수 없습니다. 원인 미상의 실패입니다."
fi
echo "============================================="
